    private val byKey: Map<String, Exercise> = all.associateBy { it.key }

    fun get(key: String): Exercise? = byKey[key]

    fun byCategory(cat: String) = all.filter { it.category == cat }

    fun search(q: String): List<Exercise> {
        val s = q.trim().lowercase()
        if (s.isEmpty()) return emptyList()
        return all.filter { it.name.lowercase().contains(s) || it.category.lowercase().contains(s) || it.purpose.lowercase().contains(s) }
    }
