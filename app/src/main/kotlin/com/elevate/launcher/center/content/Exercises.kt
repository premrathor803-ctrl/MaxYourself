    val purpose: String,
    val startPos: String,
    val steps: List<String>,
    val mistakes: List<String>,
    val easier: String,
    val harder: String,
    val safety: String
) {
    val levelName: String get() = if (level <= 1) "Beginner" else "Intermediate"
    val timed: Boolean get() = unit == "secs"
}

